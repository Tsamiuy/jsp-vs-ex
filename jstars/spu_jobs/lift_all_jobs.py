"""Lift every JOBCRT job found by scan_jobcrt.py that is not lifted yet, and
regenerate port/spu/spu_workloads.c registering all of them.

usage (from PS3Recomp/):  python3 jstars/spu_jobs/lift_all_jobs.py
"""
import json, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
J = os.path.join(ROOT, 'jstars')
TOOLS = os.path.join(ROOT, 'ps3recomp-src', 'tools')
sys.path.insert(0, os.path.join(J, 'spu_jobs'))
import scan_jobcrt

# already lifted under hand-picked names: va -> (dir, symbol prefix stem, name)
KNOWN = {
    0x0080B700: ('spujob_80B700', 'job_80B700', 'spujob_80B700'),
    0x0080FD00: ('spujob_80FD00', 'job_80FD00', 'spujob_80FD00'),
    0x00829A80: ('crijob_asrvoice', 'cri_asrvoice', 'crijob_asrvoice'),
    0x00819780: ('crijob_atomdec', 'cri_atomdec', 'crijob_atomdec'),
    0x0080CB00: ('spujob_80CB00', 'job_80CB00', 'spujob_80CB00'),
}

def name_for(j):
    if j['va'] in KNOWN:
        return KNOWN[j['va']]
    v = '%X' % j['va']
    return ('spujob_' + v, 'job_' + v, 'spujob_' + v)

def lift(j, b):
    d, stem, _ = name_for(j)
    out = os.path.join(J, 'port', 'spu', d)
    if os.path.exists(os.path.join(out, 'spu_recomp.c')):
        return d + ': already lifted'
    bin_p = os.path.join(J, 'spu_jobs', d + '.bin')
    elf_p = os.path.join(J, 'spu_jobs', d + '.elf')
    open(bin_p, 'wb').write(b[j['off']:j['off'] + j['size']])
    py = sys.executable
    subprocess.run([py, '-I', os.path.join(TOOLS, 'wrap_spu_elf.py'), bin_p, '--entry', '0x0',
                    '--base', '0x0', '--out', elf_p], check=True, capture_output=True)
    r = subprocess.run([py, '-I', os.path.join(TOOLS, 'spu_lifter.py'), '--auto-functions', elf_p,
                        '--base', '0x0', '--code-end', hex(j['code_end']),
                        '--symbol-prefix', 'jstars_%s_' % stem, '-o', out,
                        '--source-name', 'spu_recomp.c', '--header-name', 'spu_recomp.h',
                        '--report', os.path.join(J, 'spu_jobs', 'lift_%s.json' % stem)],
                       capture_output=True, text=True)
    tail = [l.strip() for l in (r.stdout + r.stderr).splitlines() if 'lifted' in l or 'unsupported' in l]
    return '%s: rc=%d %s' % (d, r.returncode, ' | '.join(tail))

def main():
    b = open(os.path.join(J, 'EBOOT.elf'), 'rb').read()
    jobs = scan_jobcrt.scan(b)
    with ThreadPoolExecutor(4) as ex:
        for line in ex.map(lambda j: lift(j, b), jobs):
            print(line)
    # registration TU
    ext, reg = [], []
    for i, j in enumerate(jobs, 1):
        d, stem, nm = name_for(j)
        ext.append('extern void jstars_%s_spu_func_00000000(spu_context*);' % stem)
        ext.append('extern void jstars_%s_spu_recomp_register(void);' % stem)
        reg.append('    spu_begin_image(%d); jstars_%s_spu_recomp_register();' % (i, stem))
        reg.append('    spu_workload_register_img(0x%sULL, jstars_%s_spu_func_00000000, %d, "%s");'
                   % (j['fp'], stem, i, nm))
    table = '\n'.join(' *   %-16s EBOOT 0x%08X  %6d B  fp %s  --code-end 0x%X'
                      % (name_for(j)[2], j['va'], j['size'], j['fp'], j['code_end']) for j in jobs)
    src = '''/* spu_workloads.c -- registers J-Stars' lifted SPURS job binaries.
 *
 * GENERATED by jstars/spu_jobs/lift_all_jobs.py -- edit that script, not this file.
 *
 * Every JOBCRT job embedded in EBOOT.elf (found by spu_jobs/scan_jobcrt.py; it
 * includes the CRI AsrVoice and AtomDecoder jobs). Each was wrapped with
 * tools/wrap_spu_elf.py (base 0, entry 0 -- the runtime loads a job binary at
 * LS 0) and lifted with spu_lifter.py --auto-functions. Fingerprints are
 * FNV-1a-64 (the runtime's basis) over exactly sizeBinary bytes, which is what
 * spu_workload_dispatch_job() hashes.
 *
%s
 */
#include "spu_workload.h"

extern void spu_begin_image(int image_id);

%s

void jstars_spu_workloads_register(void)
{
%s
    spu_begin_image(0);
}

/* Auto-register at startup (before the game adds any SPURS workload/task). */
__attribute__((constructor)) static void jstars_spu_workloads_register_ctor(void)
{
    jstars_spu_workloads_register();
}
''' % (table, '\n'.join(ext), '\n'.join(reg))
    open(os.path.join(J, 'port', 'spu', 'spu_workloads.c'), 'w', newline='\n').write(src)
    print('wrote spu_workloads.c with', len(jobs), 'jobs')

main()
