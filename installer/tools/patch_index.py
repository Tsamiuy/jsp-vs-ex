#!/usr/bin/env python3
"""Write installer/port/patches/INDEX.md: one line per toolkit patch, for reviews and toolkit upgrades.

    python installer/tools/patch_index.py [--check]

Per patch: its line (from the number: x001-x499 fix, x500-x899 feature, x900-x999 experiment), what it does (the
patch's own first line), the files and functions it touches (from the diff's hunk headers), its switches (environment
variables the added lines read), and its upstream status from installer/port/patches/upstream.tsv (patch number, tab,
status; a patch not listed there is "J-Stars"). --check exits 1 when INDEX.md is not up to date, without writing it.
Standard library only.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PATCHES = ROOT / "installer" / "port" / "patches"
INDEX = PATCHES / "INDEX.md"
UPSTREAM = PATCHES / "upstream.tsv"
GROUPS = {"0": "build", "1": "SPURS", "2": "GCM/D3D12", "3": "audio", "6": "runtime/HLE/pad"}


def line_of(num):
    k = int(num[1:])
    return "fix" if k < 500 else "feature" if k < 900 else "experiment"


def upstream_table():
    t = {}
    if UPSTREAM.exists():
        for row in UPSTREAM.read_text(encoding="utf-8").splitlines():
            if row.strip() and not row.startswith("#") and "\t" in row:
                num, status = row.split("\t", 1)
                t[num.strip()] = status.strip()
    return t


def describe(path):
    text = path.read_text(encoding="utf-8")
    first = text.splitlines()[0] if text else ""
    m = re.match(r"Patch \d+:\s*(.*)", first)
    what = (m.group(1) if m else first).strip()
    files, funcs, envs = [], [], []
    for ln in text.splitlines():
        if ln.startswith("+++ b/"):
            f = ln[6:].strip()
            if f not in files:
                files.append(f)
        elif ln.startswith("@@"):
            m = re.search(r"@@[^@]*@@\s*(.*)", ln)
            ctx = m.group(1) if m else ""
            m2 = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", ctx)
            if m2 and m2.group(1) not in funcs and m2.group(1) not in ("if", "for", "while", "switch", "sizeof"):
                funcs.append(m2.group(1))
        elif ln.startswith("+") and not ln.startswith("+++"):
            for e in re.findall(r'getenv\("([A-Z0-9_]+)"\)', ln):
                if e not in envs:
                    envs.append(e)
    return what, files, funcs, envs


def build():
    ups = upstream_table()
    rows = []
    for p in sorted(PATCHES.glob("*.patch")):
        num = p.name.split("-", 1)[0]
        what, files, funcs, envs = describe(p)
        short = [f.rsplit("/", 1)[-1] for f in files]
        rows.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            num, line_of(num), what.replace("|", "/"), ", ".join(short),
            ", ".join(funcs[:6]) + (" ..." if len(funcs) > 6 else ""),
            ", ".join(envs[:4]) + (" ..." if len(envs) > 4 else ""), ups.get(num, "J-Stars")))
    head = [
        "# Toolkit patches (generated by installer/tools/patch_index.py, do not edit)",
        "",
        "Applied in name order to the pinned toolkit by installer/tools/export_toolkit.py. Groups by first digit: "
        + ", ".join("%s %s" % (k, v) for k, v in GROUPS.items()) + ". Line by the rest: x001-x499 fix, x500-x899 "
        "feature, x900-x999 experiment. Upstream status comes from upstream.tsv. \"Functions\" are the hunk "
        "contexts, a hint for clashes, not a complete list. \"Switches\" are the environment variables the patch reads.",
        "",
        "| # | Line | What it does | Files | Functions | Switches | Upstream |",
        "|---|---|---|---|---|---|---|",
    ]
    return "\n".join(head + rows) + "\n"


def main():
    out = build()
    if "--check" in sys.argv[1:]:
        cur = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if cur != out:
            print("INDEX.md is out of date: run installer/tools/patch_index.py")
            return 1
        print("INDEX.md is up to date")
        return 0
    INDEX.write_text(out, encoding="utf-8", newline="\n")
    print("wrote %s (%d patches)" % (INDEX.relative_to(ROOT), out.count("\n| ") - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
