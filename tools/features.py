#!/usr/bin/env python3
"""Features page: docs/features.tsv -> docs/FEATURES.md (generated; never hand-edited), and its links with ROADMAP.md.

Adapted from tools/features.py of undecuple's Project Helghast (MIT, https://github.com/undecuple/project-helghast): the TSV, the
page and the staleness check come from there; the id column and the ROADMAP checks are new here.

    python3 tools/features.py            # regenerate docs/FEATURES.md
    python3 tools/features.py --check    # exit 1 when the page is stale, the data is malformed, a link points at a
                                         # file that is not in the repository, or ROADMAP.md and the data disagree
    python3 tools/features.py --root DIR # another repository root (the test's fixture)

Data format of docs/features.tsv (plain tab-separated, every row 8 cells, no straight double quotes, so GitHub can
show it as a table; lines starting with # are comments):

    id       a short stable name (lower case, digits and hyphens). It is the row's anchor on the page, and
             ROADMAP.md cites a row with a link to FEATURES.md#id. Never reuse or rename an id that ROADMAP cites.
    kind     game = a feature of the PS3 game and how far the port reproduces it
             port = something the port adds or changes
    area     grouping on the page (same text = same table, in order of first use)
    feature  short name
    detail   game rows: what the PS3 game does; port rows: what the feature does
    status   game rows: works | partial | not yet | unverified | n/a
             port rows: available | in progress | planned
    evidence game rows: where the status was recorded (a test, a dated note, a pull request), with links written from
             the repository root; port rows: the default (on, off, or opt-in)
    note     optional short remark; port rows: the setting that controls it, if any, first

Rules: "works" and "available" only with recorded evidence; a path that exists in code but was never run is
"unverified". Evidence must be public: notes, tests and pull requests, never game screenshots.

ROADMAP.md checks (a list item's indented continuation lines belong to the item): every link to FEATURES.md#id names
an existing row; a ROADMAP line that cites a row carries the marker that matches its status (done = works or
available, in progress = partial, unverified or in progress, planned = not yet or planned); and every planned port
row is cited by ROADMAP.md.
"""
import argparse
import io
import pathlib
import re
import sys

DATA = "docs/features.tsv"
PAGE = "docs/FEATURES.md"
ROADMAP = "docs/ROADMAP.md"
HEADER = "<!-- Generated by tools/features.py from docs/features.tsv. Do not edit by hand: edit the data and rerun. -->"
COLUMNS = ("id", "kind", "area", "feature", "detail", "status", "evidence", "note")

GAME_STATUS = {"works": "works", "partial": "partial", "not yet": "not yet", "unverified": "not yet verified",
               "n/a": "not applicable"}
GAME_MEANING = {"works": "checked in a run", "partial": "runs, with known gaps",
                "not yet": "not reached or not started",
                "unverified": "in the code, never run", "n/a": "has no equivalent on PC"}
PORT_STATUS = ("available", "in progress", "planned")
# ROADMAP markers and the statuses each one may stand for.
MARKERS = {"✅": {"works", "available"}, "🔧": {"partial", "unverified", "in progress"}, "📋": {"not yet", "planned"}}
ID = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*$")
CITE = re.compile(r"FEATURES\.md#([a-z0-9-]+)")


def read_rows(root):
    """Rows of the TSV as dicts, in file order, with the line number under 'line'. Raises ValueError on a bad file."""
    text = (root / DATA).read_text(encoding="utf-8")
    lines = [(i + 1, l) for i, l in enumerate(text.splitlines()) if l.strip() and not l.lstrip().startswith("#")]
    if not lines:
        raise ValueError(f"{DATA}: empty")
    head = lines[0][1].split("\t")
    if tuple(head) != COLUMNS:
        raise ValueError(f"{DATA}: header must be {' '.join(COLUMNS)}, got {' '.join(head)}")
    rows, ids = [], set()
    for ln, l in lines[1:]:
        if '"' in l:   # GitHub's TSV viewer reads a straight double quote as CSV quoting
            raise ValueError(f"{DATA}:{ln}: straight double quote; use “ ” or ' inside a field")
        cells = l.split("\t")
        if len(cells) == len(COLUMNS) - 1:   # editors strip a trailing tab: an empty note is allowed
            cells.append("")
        if len(cells) != len(COLUMNS):
            raise ValueError(f"{DATA}:{ln}: {len(cells)} columns, expected {len(COLUMNS)}")
        row = dict(zip(COLUMNS, (c.strip() for c in cells)))
        row["line"] = ln
        if not ID.match(row["id"]):
            raise ValueError(f"{DATA}:{ln}: id '{row['id']}' must be lower case letters, digits and hyphens")
        if row["id"] in ids:
            raise ValueError(f"{DATA}:{ln}: id '{row['id']}' used twice")
        ids.add(row["id"])
        if row["kind"] not in ("game", "port"):
            raise ValueError(f"{DATA}:{ln}: kind must be game or port")
        allowed = GAME_STATUS if row["kind"] == "game" else PORT_STATUS
        if row["status"] not in allowed:
            raise ValueError(f"{DATA}:{ln}: {row['kind']} status '{row['status']}' not in {', '.join(allowed)}")
        if not row["feature"]:
            raise ValueError(f"{DATA}:{ln}: empty feature")
        if row["kind"] == "game" and row["status"] == "works" and not row["evidence"]:
            raise ValueError(f"{DATA}:{ln}: 'works' needs evidence")
        rows.append(row)
    return rows


def cell(s):
    return s.replace("|", "\\|")


def links(text, root, problems, line):
    """Check that relative links point at files in the repository, and rewrite them from the root to docs/."""
    def rel(m):
        t = m.group(1)
        if re.match(r"(https?:|mailto:|#)", t):
            return m.group(0)
        path = t.split("#", 1)[0]
        if not (root / path).exists():
            problems.append(f"{DATA}:{line}: link {t} points at a file that is not in the repository")
        return "](" + (t[5:] if t.startswith("docs/") else "../" + t) + ")"
    return re.sub(r"\]\(([^)\s]+)\)", rel, text)


def areas(rows):
    out = []
    for r in rows:
        if r["area"] not in out:
            out.append(r["area"])
    return out


def render(rows, root, problems):
    game = [r for r in rows if r["kind"] == "game"]
    port = [r for r in rows if r["kind"] == "port"]
    o = io.StringIO()
    w = o.write
    w(HEADER + "\n")
    w("# Features\n\n")
    w("What the port adds or changes compared with the PS3 game (section 1), and how far the port reproduces the "
      "game's own features (section 2). Every status rests on a recorded result: a note, a test or a pull request. "
      "Anything not listed has not been checked. Options that change gameplay are opt-in. "
      "The order of the planned items: [ROADMAP.md](ROADMAP.md).\n\n")
    counts = {s: sum(1 for r in port if r["status"] == s) for s in PORT_STATUS}
    w(f"Port features: {counts['available']} available, {counts['in progress']} in progress, "
      f"{counts['planned']} planned.\n\n")

    w("## 1. What the port adds\n\n")
    for a in areas(port):
        w(f"### {a}\n\n| Feature | What it does | State | Default | Setting, notes |\n|---|---|---|---|---|\n")
        for r in (x for x in port if x["area"] == a):
            note = links(r["note"], root, problems, r["line"])
            w(f"| <a id=\"{r['id']}\"></a>{cell(r['feature'])} | {cell(links(r['detail'], root, problems, r['line']))} "
              f"| {r['status']} | {cell(r['evidence'])} | {cell(note)} |\n")
        w("\n")

    w("## 2. The PS3 game's features in the port\n\n")
    w("| Status | Meaning | Count |\n|---|---|---|\n")
    for s in GAME_STATUS:
        w(f"| {GAME_STATUS[s]} | {GAME_MEANING[s]} | {sum(1 for r in game if r['status'] == s)} |\n")
    w("\n")
    for a in areas(game):
        w(f"### {a}\n\n| Feature | On the PS3 | In the port | Evidence |\n|---|---|---|---|\n")
        for r in (x for x in game if x["area"] == a):
            note = f": {cell(r['note'])}" if r["note"] else ""
            ev = links(r["evidence"], root, problems, r["line"])
            w(f"| <a id=\"{r['id']}\"></a>{cell(r['feature'])} | {cell(r['detail'])} "
              f"| **{GAME_STATUS[r['status']]}**{note} | {cell(ev)} |\n")
        w("\n")
    return o.getvalue()


def check_roadmap(rows, root):
    """Problems between ROADMAP.md and the data (see the module docstring)."""
    p = root / ROADMAP
    if not p.exists():
        return [f"{ROADMAP} missing"]
    by_id = {r["id"]: r for r in rows}
    problems, cited = [], set()
    # A list item and its indented continuation lines count as one line (numbered by the item's first line).
    items = []
    for n, l in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
        if items and l.startswith("  ") and l.strip() and items[-1][1].lstrip().startswith("- "):
            items[-1] = (items[-1][0], items[-1][1] + " " + l.strip())
        else:
            items.append((n, l))
    for n, l in items:
        ids = CITE.findall(l)
        if not ids:
            continue
        marks = [m for m in MARKERS if m in l]
        for i in ids:
            cited.add(i)
            r = by_id.get(i)
            if not r:
                problems.append(f"{ROADMAP}:{n}: FEATURES.md#{i} matches no row of {DATA}")
                continue
            if len(marks) != 1:
                problems.append(f"{ROADMAP}:{n}: a line that cites #{i} needs exactly one of {' '.join(MARKERS)}")
            elif r["status"] not in MARKERS[marks[0]]:
                problems.append(f"{ROADMAP}:{n}: {marks[0]} but #{i} is '{r['status']}' in {DATA}:{r['line']}")
    for r in rows:
        if r["kind"] == "port" and r["status"] == "planned" and r["id"] not in cited:
            problems.append(f"{DATA}:{r['line']}: planned row #{r['id']} is not cited in {ROADMAP}")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[1]), help="repository root")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = []
    try:
        rows = read_rows(root)
    except (ValueError, OSError) as e:
        print(f"features: {e}", file=sys.stderr)
        return 1
    page = render(rows, root, problems)
    problems += check_roadmap(rows, root)
    out = root / PAGE
    if a.check:
        if not out.exists():
            problems.append(f"{PAGE} missing (run tools/features.py)")
        elif out.read_text(encoding="utf-8") != page:
            problems.append(f"{PAGE} is stale (run tools/features.py)")
    if problems:
        print("features: problems:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1
    if not a.check:
        out.write_text(page, encoding="utf-8", newline="\n")
    print(f"features: {'OK' if a.check else PAGE} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
